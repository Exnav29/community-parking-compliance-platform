"""Generate docs/security/PERMISSION_MATRIX.md from the code (core/authz.py + core/pbac.py), so the documentation cannot drift.

Usage: python scripts/gen_permission_matrix.py   (CI re-runs it and fails if the committed file differs)
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps" / "frappe_cpcp"))

from frappe_cpcp.core import pbac  # noqa: E402
from frappe_cpcp.core.authz import CAPABILITY_CLASS, MATRIX, Role  # noqa: E402

ROLES = [r for r in Role if r not in (Role.PLATFORM_ADMIN, Role.ESTATE_MANAGER)]


def main() -> None:
    lines = [
        "# Permission matrix (generated)",
        "",
        "> Generated by `scripts/gen_permission_matrix.py` from `apps/frappe_cpcp/frappe_cpcp/core/authz.py`. Do not edit by hand.",
        "",
        "Letters: **R** read, **C** create, **U** update/operate, **A** approve, **V** aggregate view only, **S** only own/assigned records, "
        "**G** only with an approved, time-limited, independently approved grant. Blank = no access. "
        "Estate Managers use the Org Admin column, limited to appointed estates. The SaaS platform operator has **no** routine tenant-data access.",
        "",
        "RBAC is necessary but never sufficient for sensitive data (PRD v1.8). Capabilities marked **PBAC** additionally require a server-verified purpose "
        "(see below) and are journaled on every attempt.",
        "",
        "| Capability | Data class | PBAC | " + " | ".join(r.value for r in ROLES) + " |",
        "|---|---|---|" + "|".join("---" for _ in ROLES) + "|",
    ]
    pbac_caps = {"gate_operations", "contact_responsible", "resident_registry", "visitor_log", "triage_reports", "emergency_access", "access_review"}
    for cap, row in MATRIX.items():
        cls = CAPABILITY_CLASS.get(cap)
        lines.append(f"| `{cap}` | {cls.value if cls else 'STAFF_OPERATIONAL'} | {'PBAC' if cap in pbac_caps else ''} | "
                     + " | ".join(row.get(r, "") for r in ROLES) + " |")
    lines += [
        "",
        "## Purposes (core/pbac.py)",
        "",
        "| Purpose | Server-verified conditions | Disclosure |",
        "|---|---|---|",
        "| `gate_entry` / `gate_exit` | Officer has a live shift at this estate on a non-revoked device, shift not expired, any claimed gate equals the shift's gate. Supervisors: estate scope, journaled. | " + ", ".join(pbac.FIELDS[pbac.Disclosure.GATE_MINIMUM]) + " |",
        "| `assigned_case` | Case exists, is open, belongs to the officer (assignment), same estate, officer on duty, target plate/unit is the case's own. Reassigning or closing the case ends access. | " + ", ".join(pbac.FIELDS[pbac.Disclosure.CASE_CONTACT]) + " (numbers only via the call/SMS action) |",
        "| `supervisor_review` | Manager within the case's estate; journaled and reviewable. | as `assigned_case` |",
        "| `emergency` | Unexpired break-glass grant raised by the same person for ONE household in ONE estate; independent review required. | " + ", ".join(pbac.FIELDS[pbac.Disclosure.EMERGENCY_CONTACT]) + " |",
        "",
        "## Denial reason codes (journal)",
        "",
        ", ".join(f"`{c.value}`" for c in pbac.Code),
        "",
    ]
    out = ROOT / "docs" / "security" / "PERMISSION_MATRIX.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
